#!/usr/bin/env node
/**
 * OnoForge 40K — BSData baseline harness scaffold
 *
 * Purpose: capture deterministic, serialized outputs from the existing BSData
 * parser before extraction. This file intentionally does NOT import or modify
 * the application yet. The current monolith is browser-oriented and does not
 * expose its parser as a Node module.
 *
 * Baseline contract:
 *   - normal unit
 *   - multiple profiles
 *   - multiple weapons
 *   - weapon abilities
 *   - optional/missing characteristics
 *   - wargear/options
 *   - BSData edge case
 *
 * The harness becomes executable only after the adapter layer below is wired
 * to the verified index.html parser without changing parser behavior.
 */

const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const sourcePath = path.join(repoRoot, 'index.html');
const fixtureDir = path.join(repoRoot, 'tests', 'fixtures', 'bsdata-baseline');

function readSource() {
  return fs.readFileSync(sourcePath, 'utf8');
}

function stableSerialize(value) {
  return JSON.stringify(value, Object.keys(value || {}).sort(), 2);
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function ensureFixtureDir() {
  fs.mkdirSync(fixtureDir, { recursive: true });
}

function writeFixture(name, value) {
  ensureFixtureDir();
  const output = stableSerialize(value) + '\n';
  fs.writeFileSync(path.join(fixtureDir, `${name}.json`), output, 'utf8');
}

function main() {
  const source = readSource();
  assert(source.includes('function bsUnitFromEntry'), 'BSData parser entry point not found');
  assert(source.includes('function collectBSDataObjects'), 'BSData collector not found');
  assert(source.includes('window.__BS_OBJECT_MAP'), 'Expected current object-map dependency not found');

  console.log('BSData baseline harness scaffold verified.');
  console.log(`Source: ${sourcePath}`);
  console.log('Runtime adapter is intentionally not wired yet.');
  console.log('No baseline fixtures were generated by this scaffold.');
}

main();
