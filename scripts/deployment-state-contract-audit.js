const fs=require('fs');
const vm=require('vm');
const source=fs.readFileSync('deployment-state.js','utf8');
const context={window:{}};
vm.runInNewContext(source,context);
const api=context.window.OnoForgeDeploymentState;
function check(name,ok){if(!ok){console.error('FAIL:',name);process.exitCode=1;}else console.log('PASS:',name);}
check('contract exported',!!api);
const state={objectiveMapMissionKey:'Mission A ↔ Mission B',objectiveMapLayout:'A'};
check('deployment key',api.deploymentPlanKey(state)==='Mission A ↔ Mission B|A');
check('invalid layout defaults A',api.deploymentPlanKey({objectiveMapMissionKey:'M',objectiveMapLayout:'Z'})==='M|A');
check('deployment plans initialize',api.ensureDeploymentPlans(state)&&typeof state.deploymentPlans==='object');
check('deployment position rounds to 0.1',api.setDeploymentPlanPosition(state,'u1',12.34,7.86)&&state.deploymentPlans['Mission A ↔ Mission B|A'].positions.u1.x===12.3&&state.deploymentPlans['Mission A ↔ Mission B|A'].positions.u1.y===7.9);
check('deployment position reads canonical shape',api.deploymentPlanPosition(state,'u1').source==='deployment-plan');
check('invalid deployment position rejected',api.setDeploymentPlanPosition(state,'u2',61,7)===false);
check('battlefield positions initialize',api.ensureBattlefieldUnitPositions(state)&&typeof state.battlefieldUnitPositions==='object');
check('battlefield position stores side/source',api.setBattlefieldUnitPosition(state,'opp','u2',20.04,30.06,'manual')&&state.battlefieldUnitPositions.u2.side==='opp'&&state.battlefieldUnitPositions.u2.x===20&&state.battlefieldUnitPositions.u2.y===30.1);
check('battlefield position reads canonical shape',api.battlefieldUnitPosition(state,'opp','u2').source==='manual');
check('side mismatch returns null',api.battlefieldUnitPosition(state,'my','u2')===null);
check('deployment clear',api.clearDeploymentPlanPosition(state,'u1')&&api.deploymentPlanPosition(state,'u1')===null);
check('battlefield clear',api.clearBattlefieldUnitPosition(state,'u2')&&api.battlefieldUnitPosition(state,'opp','u2')===null);
check('current deployment map clear',api.setDeploymentPlanPosition(state,'u3',1,1)&&api.clearDeploymentPlanForCurrentMap(state)&&Object.keys(state.deploymentPlans).length===0);
if(process.exitCode)process.exit(1);
console.log('Deployment state contract audit passed 14/14');
